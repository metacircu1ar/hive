#[test]
#[cfg(target_os = "linux")]
fn native_sandbox_probe_uses_daemon_binary_and_keeps_control_responsive() {
    let mut f = Harness::new();
    let ready = f.tmp.path().join("probe-ready");
    let release = f.tmp.path().join("probe-release");
    // The temporary path is generated by the fixture and contains no shell syntax.
    fs::write(
        &f.binary,
        format!(
            "#!/bin/sh\ntouch '{}'\nwhile test ! -e '{}'; do sleep 0.01; done\necho \
                hive-native-sandbox-ready\n",
            ready.display(),
            release.display()
        ),
    )
    .unwrap();
    f.start();
    let root = f.root.clone();
    let probe = std::thread::spawn(move || {
        runtime::client(&root, "probe", json!({"op":"sandbox_probe"})).unwrap()
    });
    support::wait::wait_until(
        Duration::from_secs(3),
        Duration::from_millis(10),
        "native sandbox probe startup",
        || ready.exists().then_some(()),
    );
    let start = Instant::now();
    assert_eq!(f.call(json!({"op":"ping"}))["status"], "running");
    assert_eq!(f.call(json!({"op":"sandbox_probe"}))["code"], "probe_busy");
    let response = f.call(json!({"op":"set_name","target":"missing","name":"probe"}));
    assert!(response.get("error").is_some(), "{response}");
    assert!(start.elapsed() < Duration::from_secs(2));
    fs::write(release, "ready").unwrap();
    let result = probe.join().unwrap();
    assert_eq!(result["outcome"], "passed", "{result}");
    assert_eq!(result["executable"], f.binary.to_str().unwrap());
    assert!(
        f.ok(json!({"op":"agents"}))["agents"]
            .as_array()
            .unwrap()
            .is_empty()
    );
    f.shutdown();
}

/// Opt-in native acceptance, separate from all mock-provider installation checks.
/// Run this executable in the deployment context (for example a systemd user service).
#[test]
#[cfg(target_os = "linux")]
#[ignore = "requires a real Codex executable selected by HIVE_NATIVE_CODEX; no login or \
    model \
    calls"]
fn native_sandbox_acceptance_without_authentication() {
    let mut f = Harness::new();
    f.binary = PathBuf::from(
        std::env::var_os("HIVE_NATIVE_CODEX")
            .expect("set HIVE_NATIVE_CODEX to the real Codex executable"),
    );
    assert!(f.binary.is_absolute());
    f.start();
    let result = f.ok(json!({"op":"sandbox_probe"}));
    assert_eq!(result["outcome"], "passed", "{result}");
    assert_eq!(result["executable"], f.binary.to_str().unwrap());
    assert!(
        f.ok(json!({"op":"agents"}))["agents"]
            .as_array()
            .unwrap()
            .is_empty()
    );
    f.shutdown();
}

/// This must run in the intended daemon context, independently of mock-provider checks.
#[test]
#[cfg(target_os = "linux")]
#[ignore = "requires HIVE_NATIVE_CLAUDE and native Bubblewrap; no login or model calls"]
fn claude_sandbox_acceptance_without_authentication() {
    let mut f = Harness::builder(Provider::Claude).build();
    let native = PathBuf::from(
        std::env::var_os("HIVE_NATIVE_CLAUDE")
            .expect("set HIVE_NATIVE_CLAUDE to the real native Claude executable"),
    );
    assert!(native.is_absolute());
    let binary = f.tmp.path().join("claude");
    fs::remove_file(&binary).unwrap();
    std::os::unix::fs::symlink(native, &binary).unwrap();
    f.start();
    let result = f.ok(json!({"op":"claude_sandbox_probe"}));
    assert_eq!(result["outcome"], "passed", "{result}");
    assert_eq!(result["executable"], binary.to_str().unwrap());
    assert!(
        f.ok(json!({"op":"agents"}))["agents"]
            .as_array()
            .unwrap()
            .is_empty()
    );
    f.shutdown();
}
