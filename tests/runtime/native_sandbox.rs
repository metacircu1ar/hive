use super::*;

#[test]
#[cfg(target_os = "linux")]
fn native_sandbox_probe_serializes_non_utf8_executable_paths() {
    use std::{ffi::OsString, os::unix::ffi::OsStringExt};
    let mut f = Harness::new();
    let binary = f
        .tmp
        .path()
        .join(OsString::from_vec(b"codex-\xff".to_vec()));
    fs::rename(&f.binary, &binary).unwrap();
    f.binary = binary;
    f.start();
    let result = f.ok(json!({"op":"sandbox_probe"}));
    assert_eq!(result["executable"], f.binary.to_string_lossy().as_ref());
    assert_eq!(result["outcome"], "passed");
    f.shutdown();
}

#[test]
fn native_sandbox_probe_retains_startup_executable_failure() {
    let mut f = Harness::new();
    let saved = f.tmp.path().join("codex-saved");
    fs::rename(&f.binary, &saved).unwrap();
    f.start();
    fs::rename(saved, &f.binary).unwrap();
    let result = f.ok(json!({"op":"sandbox_probe"}));
    assert_eq!(result["outcome"], "unavailable", "{result}");
    assert_eq!(result["code"], "provider_unavailable");
    f.shutdown();
}

